# -*- coding: utf-8 -*-
"""
Crash-Safe CEC2014 Ablation Runner for the Information Sciences Revision
=======================================================================

Scientific purpose
------------------
This script executes the controlled CEC2014 ablation study for the DMGSO
revision while preserving the already-frozen scientific implementation.

The ablation compares five deterministic algorithmic configurations:

    V0 : Pure directional sensing
    V1 : V0 + adaptive step regulation
    V2 : V1 + long-range sensing
    V3 : V2 + memory fusion
    V4 : Full DMGSO, including relocation and policy-like gating

The scientific objective of this experiment is not to introduce new
algorithmic behavior, but to quantify the incremental contribution of the
predefined DMGSO components under matched deterministic configurations.

Revision protocol
-----------------
Main experimental settings:

    Benchmark suite          : CEC2014
    Functions                : F1-F30
    Dimension                : D = 30
    Deterministic configs    : run_id = 0,...,9
    Variants                 : V0-V4
    Maximum FE budget        : 300,000 evaluations per configuration
    Refinement phase         : disabled
    Trace recording          : disabled in the main run

This yields:

    30 functions × 10 deterministic configurations × 5 variants
    = 1,500 run-level records.

Important interpretation of "run_id"
------------------------------------
DMGSO is deterministic. Therefore, run_id does NOT denote an independent
stochastic realization. Instead, it indexes a deterministic initial/configuration
state generated by the frozen implementation.

The same run_id is used across V0-V4 for a given benchmark function. This
preserves a paired experimental design: differences among variants are evaluated
under matched deterministic configurations rather than unrelated starts.

Scientific implementation freeze
---------------------------------
This file is intentionally only an execution-safety wrapper. It imports and uses
the frozen revision implementation from:

    run_ablation_dmgso_cec2014_revision.py
    dmgso_core_revision.py
    wrapper_cec2014_revision.py

It MUST NOT redefine, alter, or tune:
    - DMGSO equations,
    - component definitions,
    - benchmark functions,
    - CEC2014 optimum values,
    - FE budgets,
    - deterministic initialization logic,
    - version semantics,
    - stopping rules.

No function-specific or benchmark-specific parameter tuning is performed here.

Why this safety wrapper exists
------------------------------
Long benchmark runs can be interrupted by operating-system restarts, power loss,
terminal closure, or manual interruption. The original frozen runner protects
against accidental overwrite, but it is not resume-aware.

This wrapper therefore provides execution safety without changing the science:

    1. Existing valid results are never deleted or rewritten.
    2. Completed records are detected from their unique experimental key.
    3. Only missing records are executed.
    4. Every completed result is appended immediately to disk.
    5. Duplicate rows are rejected.
    6. Existing data are audited before continuation.
    7. FE-budget, numerical-integrity, and benchmark-error checks are enforced.
    8. A final completeness audit requires exactly 1,500 unique records.
    9. Dry-run is the default; computation requires the explicit --execute flag.

Restart behavior
----------------
If execution is interrupted, rerunning this script with --execute will:

    - read the existing CSV,
    - validate all completed rows,
    - identify the remaining experimental combinations,
    - skip completed combinations,
    - continue from the next missing record.

Thus, previously completed optimization results are preserved exactly as written.

Raw-data policy
---------------
The run-level CSV is treated as the primary raw experimental record:

    cec2014/raw/ablation_cec2014_run_summary_revision.csv

This file is append-only during the active experiment. It is never overwritten by
this script. Derived function-level summaries are written separately to the
processed-data directory by the frozen summary routine.

Benchmark error definition
--------------------------
For every run:

    error = best_f - f_opt

where f_opt is the declared CEC2014 global optimum for the corresponding
benchmark function.

A materially negative benchmark error (< -1e-8) is treated as a pipeline failure.
Only negligible floating-point round-off within tolerance is accepted by the
frozen validation routine.

FE-budget interpretation
------------------------
FE_budget_max is the common maximum objective-function-evaluation allowance.
The realized fe_used value is stored explicitly for every run and must satisfy:

    1 <= fe_used <= FE_budget_max

The wrapper does not reinterpret FE usage or convert it into wall-clock cost.

Reproducibility and provenance
------------------------------
This script is designed for transparent use by co-authors, reviewers, or other
researchers. The scientific results remain attributable to the frozen DMGSO
implementation; this wrapper only provides data-integrity and recovery logic.

Any future modification to the scientific implementation should trigger a new
code version, new provenance hash, and a new experimental run rather than silent
reuse of an existing raw-data file.
"""

