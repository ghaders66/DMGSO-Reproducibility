def make_objective(problem):
    """Return the COCO objective as a plain deterministic callable."""
    return lambda x: float(problem(x))


def run_one(
    problem,
    topology: str,
    run_id: int,
    fopt_lookup: Dict[Tuple[int, int, int], float],
) -> Dict:
    """
    Run one revision topology while patching only build_directions in memory.
    """
    D = int(problem.dimension)
    fid = int(problem.id_function)
    iid = int(problem.id_instance)

    budget = int(BUDGET_MULT * D)

    lb = np.asarray(
        problem.lower_bounds,
        dtype=np.float64,
    )

    ub = np.asarray(
        problem.upper_bounds,
        dtype=np.float64,
    )

    original_builder = dmgso_core.build_directions

    def patched_build_directions(
        D_in: int,
        k_diag: int = 8,
    ) -> np.ndarray:
        # k_diag is intentionally ignored here. The topology definition is
        # frozen by the revision experiment, while all other core logic remains
        # unchanged.
        return build_revision_directions(
            D_in,
            topology,
        )

    dmgso_core.build_directions = patched_build_directions

    try:
        cfg = DMGSOConfig(
            version="V4",
            D=D,
            FE_budget=budget,
            trace_enable=False,
            refine_enable=False,
        )

        t0 = time.perf_counter()

        result = dmgso_optimize(
            f=make_objective(problem),
            lb=lb,
            ub=ub,
            cfg=cfg,
            run_id=run_id,
        )

        wall = time.perf_counter() - t0

    finally:
        dmgso_core.build_directions = original_builder

    f_opt = float(
        fopt_lookup[(fid, iid, D)]
    )

    best_f = float(result.best_f)
    error_corrected = best_f - f_opt

    if not np.isfinite(best_f):
        raise RuntimeError(
            f"Non-finite best_f for {topology}, F{fid}, I{iid}, D={D}, run={run_id}."
        )

    if not np.isfinite(error_corrected):
        raise RuntimeError(
            "Non-finite corrected error."
        )

    if error_corrected < -ERROR_TOL:
        raise RuntimeError(
            f"Materially negative corrected error: {error_corrected}"
        )

    fe_used = int(result.fe_used)

    if fe_used > budget:
        raise RuntimeError(
            f"FE-budget violation: used {fe_used}, budget {budget}."
        )

    topology_info = direction_audit(
        D,
        topology,
    )

    return {
        "suite": "COCO/BBOB",
        "topology": topology,
        "function_id": fid,
        "instance_id": iid,
        "dimension": D,
        "run_id": int(run_id),
        "FE_budget": budget,
        "budget_mult": BUDGET_MULT,
        "fe_used": fe_used,
        "best_f": best_f,
        "f_opt_official": f_opt,
        "error_corrected": float(error_corrected),
        "n_accept": int(result.n_accept),
        "n_reloc": int(result.n_reloc),
        "wall_time_sec": float(wall),
        **topology_info,
        "status": "ok",
    }


