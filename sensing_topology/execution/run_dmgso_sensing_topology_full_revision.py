"""
DMGSO Reviewer-Driven Sensing-Topology Full Experiment (Crash-Safe)
===================================================================

Purpose
-------
This revision-only experiment addresses the reviewer request to investigate
the number and topology of deterministic sensing directions, especially at
D = 20 and D = 40.

IMPORTANT:
- The historical DMGSO implementation is NOT modified on disk.
- Historical DMGSO results are NOT rerun here because complete frozen results
  already exist for D = 20 and D = 40 under the original topology.
- This runner generates ONLY the three new controlled topology variants:
      AXIS_ONLY
      FIXED8_UNIQUE
      DIM_ADAPTIVE
- Final analysis must combine these new results with the frozen historical
  DMGSO results.

Experimental protocol
---------------------
COCO/BBOB:
    24 functions
    15 instances: 1-5 and 71-80
    dimensions: D = 20, 40
    run_id: 0, 1, 2, 3, 4
    FE_budget = 1000 * D

New runs:
    3 topologies * 24 functions * 15 instances * 2 dimensions * 5 run_ids
    = 10,800 runs

Historical topology
-------------------
The manuscript implementation uses:
    K = 2D + 8 stored directions

The original parity-based diagonal construction stores 8 diagonal directions
but yields only 2 unique diagonal patterns. Historical results are preserved
exactly as previously generated and are not overwritten or silently corrected.

Revision-only controlled topologies
-----------------------------------
AXIS_ONLY
    2D axis-aligned directions only.

FIXED8_UNIQUE
    2D axis directions + 8 deterministic unique dense sign-pattern directions.
    This keeps the same stored-direction count and normal per-iteration FE cost
    as the historical topology while removing diagonal duplication.

DIM_ADAPTIVE
    2D axis directions + D deterministic unique dense sign-pattern directions.
    This tests increased directional coverage whose cost scales with dimension.

The unique dense sign patterns are deterministic and generated by a Gray-code
construction. No stochastic sampling is introduced.

Crash-safe behavior
-------------------
- One CSV row is appended immediately after every completed run.
- Every row is flushed and fsynced.
- On restart, existing complete experiment keys are detected and skipped.
- Duplicate keys are refused.
- The runner never overwrites historical source data.
- The output file may be resumed safely after interruption.

Corrected BBOB error
--------------------
For every new run:
    error_corrected = best_f - f_opt_official

The official f* values are read from the frozen revision reference file.

Output
------
sensing_topology/raw/
    topology_full_run_summary_revision.csv

sensing_topology/logs/
    topology_full_run_audit_revision.txt

After all 10,800 rows are complete, a strict final audit is performed.
"""

