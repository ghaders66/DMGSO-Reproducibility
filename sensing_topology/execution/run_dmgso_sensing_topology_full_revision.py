def load_fopt_lookup() -> Dict[Tuple[int, int, int], float]:
    """Load frozen official BBOB optima into a strict lookup table."""
    df = pd.read_csv(FOPT_PATH)

    required = {
        "function_id",
        "instance_id",
        "dimension",
        "f_opt",
    }

    missing = required - set(df.columns)

    if missing:
        raise RuntimeError(
            f"Frozen f* reference missing columns: {sorted(missing)}"
        )

    key_cols = [
        "function_id",
        "instance_id",
        "dimension",
    ]

    if df.duplicated(key_cols).any():
        raise RuntimeError(
            "Duplicate keys detected in frozen official f* reference."
        )

    lookup = {
        (
            int(row.function_id),
            int(row.instance_id),
            int(row.dimension),
        ): float(row.f_opt)
        for row in df.itertuples(index=False)
    }

    expected_keys = {
        (fid, iid, D)
        for fid in FUNCTIONS
        for iid in INSTANCES
        for D in DIMENSIONS
    }

    missing_keys = expected_keys - set(lookup)

    if missing_keys:
        raise RuntimeError(
            f"Frozen f* reference is missing {len(missing_keys)} required keys."
        )

    return lookup


