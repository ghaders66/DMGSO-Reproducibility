def read_existing_keys() -> set:
    """
    Validate an existing partial output and return its complete experiment keys.

    The output is append-only. Any duplicate key causes an immediate stop.
    """
    if not OUT_CSV.exists():
        return set()

    df = pd.read_csv(OUT_CSV)

    missing = set(FIELDNAMES) - set(df.columns)

    if missing:
        raise RuntimeError(
            f"Existing output is missing required columns: {sorted(missing)}"
        )

    if df.duplicated(KEY).any():
        duplicated = int(df.duplicated(KEY).sum())
        raise RuntimeError(
            f"Existing output contains {duplicated} duplicate experiment keys."
        )

    if len(df) > EXPECTED_ROWS:
        raise RuntimeError(
            f"Existing output has {len(df)} rows, exceeding expected "
            f"{EXPECTED_ROWS}."
        )

    bad_topology = set(df["topology"].astype(str)) - set(TOPOLOGIES)

    if bad_topology:
        raise RuntimeError(
            f"Unexpected topologies in existing output: {sorted(bad_topology)}"
        )

    if (
        pd.to_numeric(df["fe_used"])
        > pd.to_numeric(df["FE_budget"])
    ).any():
        raise RuntimeError(
            "Existing output contains an FE-budget violation."
        )

    if not (
        df["status"].astype(str).str.lower() == "ok"
    ).all():
        raise RuntimeError(
            "Existing output contains non-ok rows."
        )

    corrected = pd.to_numeric(
        df["error_corrected"],
        errors="coerce",
    ).to_numpy(dtype=float)

    if not np.isfinite(corrected).all():
        raise RuntimeError(
            "Existing output contains non-finite corrected errors."
        )

    if (corrected < -ERROR_TOL).any():
        raise RuntimeError(
            "Existing output contains materially negative corrected errors."
        )

    return {
        (
            str(row.topology),
            int(row.function_id),
            int(row.instance_id),
            int(row.dimension),
            int(row.run_id),
        )
        for row in df.itertuples(index=False)
    }


def append_row_crash_safe(row: Dict) -> None:
    """
    Append one completed run and force it to disk immediately.
    """
    file_exists = OUT_CSV.exists()

    with OUT_CSV.open(
        "a",
        newline="",
        encoding="utf-8",
    ) as stream:
        writer = csv.DictWriter(
            stream,
            fieldnames=FIELDNAMES,
        )

        if not file_exists:
            writer.writeheader()

        writer.writerow(row)

        stream.flush()
        os.fsync(stream.fileno())


