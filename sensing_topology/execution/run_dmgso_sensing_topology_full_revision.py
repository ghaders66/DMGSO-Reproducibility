def _canonical_key(v: np.ndarray) -> Tuple[int, ...]:
    """Canonicalize a dense ±1 sign vector up to global sign."""
    s = np.where(v >= 0.0, 1, -1).astype(int)

    if s[0] < 0:
        s = -s

    return tuple(int(x) for x in s)


def _gray_code_sign_patterns(D: int, k: int) -> np.ndarray:
    """
    Construct k deterministic unique dense ±1 directions.

    Global sign complements are treated as the same sign-pattern family during
    construction, preventing trivial opposite duplicates from consuming the
    requested diagonal diversity.
    """
    if k <= 0:
        return np.empty((0, D), dtype=np.float64)

    patterns: List[np.ndarray] = []
    seen = set()

    candidate = 1
    max_candidates = max(10000, 1000 * k)

    while len(patterns) < k and candidate <= max_candidates:
        gray = candidate ^ (candidate >> 1)

        v = np.ones(D, dtype=np.float64)

        nbits = max(
            2,
            int(np.ceil(np.log2(D + k + 2))),
        )

        for j in range(D):
            bit_index = (j + candidate) % nbits
            bit = (gray >> bit_index) & 1

            if bit:
                v[j] = -1.0

        # A dense diagonal must contain both signs.
        if np.all(v > 0.0) or np.all(v < 0.0):
            candidate += 1
            continue

        key = _canonical_key(v)

        if key not in seen:
            seen.add(key)
            patterns.append(v)

        candidate += 1

    if len(patterns) != k:
        raise RuntimeError(
            f"Could not construct {k} unique deterministic "
            f"diagonal patterns for D={D}."
        )

    arr = np.vstack(patterns).astype(np.float64)
    arr /= np.linalg.norm(arr, axis=1, keepdims=True)

    return arr


def build_revision_directions(D: int, mode: str) -> np.ndarray:
    """Build one controlled revision topology."""
    I = np.eye(D, dtype=np.float64)

    axes = np.vstack(
        [
            direction
            for j in range(D)
            for direction in (I[j], -I[j])
        ]
    )

    if mode == "AXIS_ONLY":
        return axes

    if mode == "FIXED8_UNIQUE":
        diagonals = _gray_code_sign_patterns(D, 8)
        return np.vstack([axes, diagonals])

    if mode == "DIM_ADAPTIVE":
        diagonals = _gray_code_sign_patterns(D, D)
        return np.vstack([axes, diagonals])

    raise ValueError(
        f"Unknown revision topology: {mode}"
    )


def direction_audit(D: int, mode: str) -> Dict[str, int]:
    """Return direction-count and nominal full-iteration FE accounting."""
    dirs = build_revision_directions(D, mode)

    rounded = np.round(
        dirs,
        decimals=14,
    )

    unique = np.unique(
        rounded,
        axis=0,
    )

    stored = int(len(dirs))
    unique_count = int(len(unique))
    duplicates = stored - unique_count

    return {
        "stored_directions": stored,
        "unique_directions": unique_count,
        "duplicate_directions": duplicates,
        "normal_iteration_fe": 2 * stored + 1,
    }


def validate_topology_design() -> None:
    """Fail fast if the frozen revision topology design has changed."""
    expected = {
        (20, "AXIS_ONLY"): (40, 40, 0, 81),
        (20, "FIXED8_UNIQUE"): (48, 48, 0, 97),
        (20, "DIM_ADAPTIVE"): (60, 60, 0, 121),
        (40, "AXIS_ONLY"): (80, 80, 0, 161),
        (40, "FIXED8_UNIQUE"): (88, 88, 0, 177),
        (40, "DIM_ADAPTIVE"): (120, 120, 0, 241),
    }

    for (D, mode), target in expected.items():
        audit = direction_audit(D, mode)

        observed = (
            audit["stored_directions"],
            audit["unique_directions"],
            audit["duplicate_directions"],
            audit["normal_iteration_fe"],
        )

        if observed != target:
            raise RuntimeError(
                f"Topology design mismatch for D={D}, {mode}.\n"
                f"Expected: {target}\n"
                f"Observed: {observed}"
            )


