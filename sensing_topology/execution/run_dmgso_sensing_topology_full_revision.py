def main() -> None:
    print("=" * 88)
    print("DMGSO SENSING-TOPOLOGY FULL RUN — CRASH-SAFE REVISION EXPERIMENT")
    print("=" * 88)

    RAW_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    LOG_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    verify_fopt_reference()
    validate_topology_design()

    print("[PASS] Frozen official f* SHA-256 verified.")
    print("[PASS] Revision topology design verified.")

    fopt_lookup = load_fopt_lookup()
    completed = read_existing_keys()

    print(
        f"[INFO] Existing complete rows: {len(completed)} / {EXPECTED_ROWS}"
    )

    if len(completed) == EXPECTED_ROWS:
        print("[INFO] Dataset is already complete. Running final audit only.")
        final_audit()
        return

    suite = cocoex.Suite(
        "bbob",
        "",
        "",
    )

    completed_now = len(completed)

    # Iterate the suite once. Each problem is used immediately and is not
    # retained after the suite advances, avoiding stale cocoex handles.
    for problem in suite:
        D = int(problem.dimension)

        if D not in DIMENSIONS:
            continue

        fid = int(problem.id_function)
        iid = int(problem.id_instance)

        if fid not in FUNCTIONS:
            continue

        if iid not in INSTANCES:
            continue

        for topology in TOPOLOGIES:
            for run_id in RUN_IDS:
                key = (
                    topology,
                    fid,
                    iid,
                    D,
                    run_id,
                )

                if key in completed:
                    continue

                row = run_one(
                    problem=problem,
                    topology=topology,
                    run_id=run_id,
                    fopt_lookup=fopt_lookup,
                )

                append_row_crash_safe(
                    row
                )

                completed.add(
                    key
                )

                completed_now += 1

