def final_audit() -> pd.DataFrame:
    """Perform a strict audit of the completed 10,800-row dataset."""
    if not OUT_CSV.exists():
        raise RuntimeError(
            "Full topology output file does not exist."
        )

    df = pd.read_csv(OUT_CSV)

    checks = []

    checks.append(
        ("Rows", len(df), EXPECTED_ROWS, len(df) == EXPECTED_ROWS)
    )

    checks.append(
        (
            "Topologies",
            df["topology"].nunique(),
            len(TOPOLOGIES),
            set(df["topology"]) == set(TOPOLOGIES),
        )
    )

    checks.append(
        (
            "Functions",
            df["function_id"].nunique(),
            24,
            set(df["function_id"].astype(int)) == FUNCTIONS,
        )
    )

    checks.append(
        (
            "Instances",
            df["instance_id"].nunique(),
            15,
            set(df["instance_id"].astype(int)) == INSTANCES,
        )
    )

    checks.append(
        (
            "Dimensions",
            sorted(df["dimension"].astype(int).unique().tolist()),
            [20, 40],
            set(df["dimension"].astype(int)) == DIMENSIONS,
        )
    )

    checks.append(
        (
            "Run IDs",
            sorted(df["run_id"].astype(int).unique().tolist()),
            RUN_IDS,
            set(df["run_id"].astype(int)) == set(RUN_IDS),
        )
    )

    duplicate_count = int(
        df.duplicated(KEY).sum()
    )

    checks.append(
        (
            "Duplicate keys",
            duplicate_count,
            0,
            duplicate_count == 0,
        )
    )

    status_bad = int(
        (df["status"].astype(str).str.lower() != "ok").sum()
    )

    checks.append(
        (
            "Non-ok rows",
            status_bad,
            0,
            status_bad == 0,
        )
    )

    budget_bad = int(
        (
            pd.to_numeric(df["fe_used"])
            > pd.to_numeric(df["FE_budget"])
        ).sum()
    )

    checks.append(
        (
            "FE-budget violations",
            budget_bad,
            0,
            budget_bad == 0,
        )
    )

    err = pd.to_numeric(
        df["error_corrected"],
        errors="coerce",
    ).to_numpy(dtype=float)

    nonfinite = int(
        (~np.isfinite(err)).sum()
    )

    negative = int(
        (err < -ERROR_TOL).sum()
    )

    checks.append(
        (
            "Non-finite corrected errors",
            nonfinite,
            0,
            nonfinite == 0,
        )
    )

    checks.append(
        (
            "Material negative corrected errors",
            negative,
            0,
            negative == 0,
        )
    )

    # Every topology × function × instance × dimension block must contain 5 runs.
    blocks = (
        df.groupby(
            [
                "topology",
                "function_id",
                "instance_id",
                "dimension",
            ],
            observed=True,
        )["run_id"]
        .nunique()
    )

    incomplete = int(
        (blocks != 5).sum()
    )

    checks.append(
        (
            "Incomplete 5-run blocks",
            incomplete,
            0,
            incomplete == 0,
        )
    )

    # Verify frozen topology counts row-by-row.
    topology_count_bad = 0

    for row in df.itertuples(index=False):
        expected = direction_audit(
            int(row.dimension),
            str(row.topology),
        )

        observed = (
            int(row.stored_directions),
            int(row.unique_directions),
            int(row.duplicate_directions),
            int(row.normal_iteration_fe),
        )

        target = (
            expected["stored_directions"],
            expected["unique_directions"],
            expected["duplicate_directions"],
            expected["normal_iteration_fe"],
        )

        if observed != target:
            topology_count_bad += 1

    checks.append(
        (
            "Topology-count mismatches",
            topology_count_bad,
            0,
            topology_count_bad == 0,
        )
    )

    passed = all(
        check[3]
        for check in checks
    )

    lines = [
        "DMGSO SENSING-TOPOLOGY FULL RUN — FINAL AUDIT",
        "=" * 72,
        "",
        f"Dataset: {OUT_CSV}",
        f"SHA-256: {sha256_file(OUT_CSV)}",
        "",
    ]

    for label, observed, expected, ok in checks:
        lines.append(
            f"[{'PASS' if ok else 'FAIL'}] "
            f"{label}: {observed} / expected {expected}"
        )

    lines.extend(
        [
            "",
            "Rows by topology:",
            df.groupby("topology").size().to_string(),
            "",
            "Rows by topology/dimension:",
            df.groupby(["topology", "dimension"]).size().to_string(),
            "",
            (
                "FINAL STATUS: FULL TOPOLOGY AUDIT PASSED"
                if passed
                else "FINAL STATUS: FULL TOPOLOGY AUDIT FAILED"
            ),
            "",
        ]
    )

    AUDIT_TXT.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )

    print()
    print("\n".join(lines))

    if not passed:
        raise RuntimeError(
            "Final full topology audit failed."
        )

    return df


